"""Build cartridges.blend from the specs in specs/ and bullets/.

Run with Blender (4.2+; developed on 5.2):

    blender --background --factory-startup --python build.py -- [options]

Options (after the "--"):
    --out PATH            .blend to write (default: cartridges.blend)
    --only KEY [KEY ...]  build only these cartridges (spec keys, e.g. 9mm 308)
    --seed N              variation seed (default 1); the same seed rebuilds the same scene
    --engine NAME         eevee (default) or cycles, for the saved file and renders
    --render DIR          also render overview, lineup and headstamp images into DIR
    --report PATH         write the measured-vs-tolerance table (markdown)
    --cpu                 Cycles only: render on the CPU even if a GPU is available
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

import bpy  # noqa: E402

from cartridges import specs  # noqa: E402
from cartridges.blender import scene as sc  # noqa: E402


def main(argv):
    ap = argparse.ArgumentParser(prog="build.py")
    ap.add_argument("--out", default=str(ROOT / "cartridges.blend"))
    ap.add_argument("--only", nargs="+")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--engine", choices=("eevee", "cycles"), default="eevee")
    ap.add_argument("--render", type=Path)
    ap.add_argument("--report", type=Path)
    ap.add_argument("--cpu", action="store_true")
    args = ap.parse_args(argv)

    t0 = time.time()
    carts = specs.load_all(keys=args.only)
    print(f"Loaded {len(carts)} specs: {', '.join(c.key for c in carts)}")

    sc.reset_scene(args.engine)
    width, depth, stats = sc.build_layout(carts, seed=args.seed)
    sc.add_studio(width, depth)
    verts = sum(len(m.vertices) for m in bpy.data.meshes)
    print(f"Built {len(stats['copies'])} copies, {len(bpy.data.meshes)} meshes, {verts:,} vertices in {time.time() - t0:.1f}s")

    report = sc.dimension_report(carts, stats)
    print(report)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(f"# Dimension check\n\nGenerated by `build.py --seed {args.seed} --report`.\n\n" + report + "\n", encoding="utf-8")

    bpy.ops.wm.save_as_mainfile(filepath=str(Path(args.out).resolve()), compress=True)
    print(f"Saved {args.out} ({width:.0f} x {depth:.0f} mm layout) in {time.time() - t0:.1f}s")

    if args.render:
        args.render.mkdir(parents=True, exist_ok=True)
        if args.engine == "cycles":
            device = "CPU" if args.cpu else sc.use_gpu()
            if args.cpu:
                bpy.context.scene.cycles.device = "CPU"
            print(f"Rendering with Cycles on {device}")
        else:
            print("Rendering with EEVEE")
        t1 = time.time()
        sc.render(args.render / "overview.jpg")
        print(f"  overview.jpg {time.time() - t1:.1f}s")
        t1 = time.time()
        sc.render_details(carts, args.render, seed=args.seed)
        print(f"  lineup.jpg, headstamps.jpg, fired.jpg {time.time() - t1:.1f}s")


if __name__ == "__main__":
    argv = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
    main(argv)
